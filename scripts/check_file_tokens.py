"""Pre-commit check: block staged files over MAX_TOKENS tokens (tokens = bytes / 4), so
no single file grows too big for an agent to read and edit in one go.

  python scripts/check_file_tokens.py       # check what's staged (run by .githooks/pre-commit)
  git config core.hooksPath .githooks        # install the hook, once per clone

Only files people or agents write by hand are checked. Lockfiles, generated code,
benchmark data and results, and binary files are skipped: see EXCLUDE and is_generated.
"""
import fnmatch
import subprocess
import sys

MAX_TOKENS = 5000
BYTES_PER_TOKEN = 4

EXCLUDE = [  # fnmatch patterns on repo paths; "*" also matches "/"
    # lockfiles
    "*.lock", "*package-lock.json", "*pnpm-lock.yaml", "*yarn.lock",
    # benchmark data and outputs, written by bench/ and review scripts
    "data/*.jsonl", "data/REVIEW_SAMPLE*", "results/*",
]
GENERATED_MARKERS = ("generated by", "@generated", "do not edit")

SPLIT_HELP = """\
Split each file along a seam it already has, so every part has one job and stays under
about {target:,} tokens (leave headroom for the next change):

  Python (.py)      Move a group of related functions or classes into a new module in
                    the same package, e.g. fow_cache/guard.py -> fow_cache/guard.py +
                    fow_cache/facts.py. Re-export from the original module
                    (`from .facts import update_facts`) so existing imports keep
                    working, then update tests that patch the moved names.
  TypeScript (.ts)  Same as Python: a new module beside it, re-exported from the
                    original file or js/src/index.ts; rerun `npm test`.
  Markdown (.md)    Move whole top-level sections into their own pages
                    (wiki/findings.md -> wiki/findings-conversations.md) and leave a
                    one-line link where each was.
  HTML (.html)      Move the <style> block into a .css file and the <script> into .js
                    files (data, rendering, controls), loaded with <link> and
                    <script src>.
  Tests             One test file per module under test.

If the file is generated or isn't written by hand (a lockfile, codegen, data or results),
add its pattern to EXCLUDE in scripts/check_file_tokens.py instead of splitting it.
Don't bypass the hook with --no-verify."""


def git(*args):
    return subprocess.run(["git", *args], check=True, capture_output=True).stdout


def staged_files():
    out = git("diff", "--cached", "--name-only", "--diff-filter=ACMR", "-z")
    return [p for p in out.decode().split("\0") if p]


def excluded(path):
    return any(fnmatch.fnmatch(path, pattern) for pattern in EXCLUDE)


def is_binary(blob):
    return b"\0" in blob[:8000]  # git's own heuristic


def is_generated(blob):
    head = blob[:500].decode(errors="ignore").lower()
    return any(marker in head for marker in GENERATED_MARKERS)


def oversized(paths, read=lambda p: git("show", f":{p}")):
    """[(path, tokens)] for checked files over the limit. Reads the staged version."""
    found = []
    for path in paths:
        if excluded(path):
            continue
        blob = read(path)
        if is_binary(blob) or is_generated(blob):
            continue
        tokens = len(blob) // BYTES_PER_TOKEN
        if tokens > MAX_TOKENS:
            found.append((path, tokens))
    return found


def main():
    found = oversized(staged_files())
    if not found:
        return 0
    print(f"Commit blocked: {len(found)} staged file(s) over {MAX_TOKENS:,} tokens (bytes / {BYTES_PER_TOKEN}).\n",
          file=sys.stderr)
    for path, tokens in found:
        print(f"  {path}: {tokens:,} tokens, {tokens - MAX_TOKENS:,} over", file=sys.stderr)
    print("\n" + SPLIT_HELP.format(target=int(MAX_TOKENS * 0.8)), file=sys.stderr)
    return 1


if __name__ == "__main__":
    sys.exit(main())
