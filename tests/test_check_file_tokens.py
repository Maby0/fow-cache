import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent / "scripts"))

import check_file_tokens as cft  # noqa: E402

SCRIPT = Path(cft.__file__)
LIMIT = cft.MAX_TOKENS * cft.BYTES_PER_TOKEN


def test_flags_only_hand_written_files_over_the_limit():
    files = {
        "fow_cache/big.py": b"x" * (LIMIT + 4),
        "fow_cache/ok.py": b"x" * LIMIT,
        "uv.lock": b"x" * (LIMIT * 2),
        "js/package-lock.json": b"x" * (LIMIT * 2),
        "data/conv-long/billing.jsonl": b"x" * (LIMIT * 2),
        "results/derived/haiku.json": b"x" * (LIMIT * 2),
        "js/src/shared.ts": b"// Generated by scripts/gen_js_shared.py. Do not edit.\n" + b"x" * LIMIT,
        "demo/demo.gif": b"GIF89a\0" + b"x" * LIMIT,
    }
    assert cft.oversized(files, read=files.__getitem__) == [("fow_cache/big.py", cft.MAX_TOKENS + 1)]


def git(cwd, *args):
    subprocess.run(["git", *args], cwd=cwd, check=True, capture_output=True)


def test_checks_the_staged_version(tmp_path):
    git(tmp_path, "init", "-q")
    big = tmp_path / "big.md"
    big.write_bytes(b"x" * (LIMIT + 4))
    git(tmp_path, "add", "big.md")
    big.write_bytes(b"small")  # unstaged edit doesn't count
    run = subprocess.run([sys.executable, str(SCRIPT)], cwd=tmp_path, capture_output=True, text=True)
    assert run.returncode == 1
    assert "big.md: 5,001 tokens" in run.stderr
    assert "Split each file" in run.stderr

    git(tmp_path, "add", "big.md")
    assert subprocess.run([sys.executable, str(SCRIPT)], cwd=tmp_path).returncode == 0
